def main():
    parser = argparse.ArgumentParser(
        description='md2blog — Turn Markdown files into a static blog in 1 second.',
        epilog='Example: python md2blog.py ./posts ./output --title "My Blog"'
    )
    parser.add_argument('input', help='Folder containing .md files')
    parser.add_argument('output', help='Output folder for generated HTML')
    parser.add_argument('--title', default='My Blog', help='Blog title')
    parser.add_argument('--description', default='A simple blog.', help='Blog description')
    parser.add_argument('--author', default='Anonymous', help='Author name')
    parser.add_argument('--url', default='/', help='Base URL for RSS/sitemap')
    
    args = parser.parse_args()
    
    print("md2blog -- 1-second static blog generator")
    print(f"   Input:  {args.input}")
    print(f"   Output: {args.output}")
    print()
    
    success = build_blog(
        args.input,
        args.output,
        blog_title=args.title,
        blog_description=args.description,
        author=args.author,
        base_url=args.url
    )
    
    if success:
        print(f"\nDone! Open {args.output}/index.html in your browser.")
    else:
        print("\nBuild failed.")

if __name__ == '__main__':
    main()
